import assert from 'node:assert/strict';
import { createSampleController } from './native-sample-controller.js';
const blob=new Blob(['sample'],{type:'video/mp4'});
let run=async()=>blob, aborted=false;
const state=createSampleController(signal=>{signal.addEventListener('abort',()=>aborted=true);return run();},20);
assert.equal(state.blob,null);
await state.generate();assert.equal(state.blob,blob);assert.equal(state.busy,false);
run=async()=>{throw Error('encoder failed')};
await assert.rejects(state.generate(),/encoder failed/);assert.equal(state.blob,blob);
run=async()=>new Blob([],{type:'video/mp4'});
await assert.rejects(state.generate(),/empty/);assert.equal(state.blob,blob);
let finish;run=()=>new Promise(resolve=>finish=resolve);
const pending=state.generate();assert.equal(state.busy,true);
await assert.rejects(state.generate(),/busy/);
await assert.rejects(pending,/timeout/);assert.equal(aborted,true);assert.equal(state.busy,false);assert.equal(state.blob,blob);
await assert.rejects(state.generate(),/reload/);
finish(new Blob(['late'],{type:'video/mp4'}));await new Promise(r=>setTimeout(r,0));assert.equal(state.blob,blob);
await assert.rejects(state.generate(),/reload/);
console.log('Native sample controller: success, failed retry, empty, busy, timeout and late completion PASS');
